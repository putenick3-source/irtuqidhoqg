$root = $PSScriptRoot
$headers = @(
  (Join-Path $root 'game\offsets\robrun_offsets.h'),
  (Join-Path $root 'game\offsets\robrun_sdk_offsets.h')
)
$out = Join-Path $root 'game\rr_autoupdate_table.h'
$rows = New-Object System.Collections.Generic.List[string]
$nField = 0; $nMethod = 0; $nUnres = 0
foreach ($h in $headers) {
  if (-not (Test-Path -LiteralPath $h)) { continue }
  foreach ($line in (Get-Content -LiteralPath $h)) {
    if ($line -notmatch '^\s*#define\s+(RR_(OFF|RVA|SF)_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+)u?\s*(/\*\s*(.*?)\s*\*/)?\s*$') { continue }
    $macro = $Matches[1]; $value = $Matches[3]; $comment = $Matches[5]
    $kind = 3; $cls = ''; $mem = ''
    if (-not [string]::IsNullOrEmpty($comment)) {
      $paren = $comment.IndexOf('(')
      $isMethod = ($paren -gt 0) -and ($comment[$paren - 1] -ne ' ')
      if ($isMethod) {
        $head = $comment.Substring(0, $paren).Trim()
        if ($head.Contains('.')) {
          $i = $head.LastIndexOf('.')
          $cls = $head.Substring(0, $i).Trim(); $mem = ($head.Substring($i + 1).Trim() -split '\s+')[0]
          if ($cls -match '^[A-Za-z_][A-Za-z0-9_.]*$' -and $mem -match '^[A-Za-z_][A-Za-z0-9_]*$') { $kind = 1 }
        }
      } elseif ($comment.Contains('.')) {
        $i = $comment.LastIndexOf('.')
        $cls = $comment.Substring(0, $i).Trim(); $mem = ($comment.Substring($i + 1).Trim() -split '\s+')[0]
        if ($cls -match '\s') { $cls = ($cls -split '\s+')[-1] }
        if ($cls -match '^[A-Za-z_][A-Za-z0-9_.]*$' -and $mem -match '^[A-Za-z_][A-Za-z0-9_]*$') { $kind = 0 }
      }
    }
    switch ($kind) { 0 { $nField++ } 1 { $nMethod++ } default { $nUnres++ } }
    $rows.Add(('    {{ "{0}", "{1}", "{2}", {3}, {4}u }},' -f $macro, $cls, $mem, $kind, $value))
  }
}
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* GENERATED by gen_autoupdate_table.ps1 - do not edit by hand. */')
[void]$sb.AppendLine('/* kind: 0 field offset, 1 method rva, 3 unresolvable (keep current value) */')
[void]$sb.AppendLine('#ifndef RR_AUTOUPDATE_TABLE_H')
[void]$sb.AppendLine('#define RR_AUTOUPDATE_TABLE_H')
[void]$sb.AppendLine('static const rr_au_row rr_au_rows[] = {')
foreach ($r in $rows) { [void]$sb.AppendLine($r) }
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('#define RR_AU_COUNT (sizeof(rr_au_rows) / sizeof(rr_au_rows[0]))')
[void]$sb.AppendLine('#endif')
Set-Content -LiteralPath $out -Value $sb.ToString() -Encoding ASCII
"rows=$($rows.Count) field=$nField method=$nMethod unres=$nUnres"

